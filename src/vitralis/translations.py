_current_lang = "English"


def set_language(lang: str) -> None:
    global _current_lang
    _current_lang = lang


def t(key: str) -> str:
    table = _TRANSLATIONS.get(_current_lang, {})
    return table.get(key, key)


def tool_tip(lang: str, key: str) -> str:
    table = _TRANSLATIONS.get(lang, {})
    return table.get(key, key)
